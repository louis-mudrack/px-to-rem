import { formatNumber, type NumberStyle } from './format';

/** Languages a px-to-rem helper can be generated for. */
export type HelperTarget = 'scss' | 'sass' | 'less' | 'stylus' | 'css' | 'js' | 'ts';

const HEADER = 'Generated by PX to REM Toolkit.';

/** `px-to-rem` → `pxToRem`, so the name is a valid JS identifier. */
function jsIdentifier(name: string): string {
    const camel = name.replace(/[-.]+([a-zA-Z0-9])/g, (_, c: string) => c.toUpperCase()).replace(/[^\w$]/g, '');
    if (!camel) {
        return 'rem';
    }
    return /^\d/.test(camel) ? `_${camel}` : camel;
}

/** `rem` → `--rem`: CSS custom functions are dashed idents. */
function cssFunctionName(name: string): string {
    return name.startsWith('--') ? name : `--${name.replace(/^-+/, '')}`;
}

/**
 * Source code of a px-to-rem helper named `functionName` with the given
 * default base, ready to paste into a new file.
 *
 * - SCSS/Sass: `@use 'sass:math'` and `math.div`; `rem(16)` and `rem(16px)`
 *   both return `1rem`; other units raise an `@error`.
 * - Stylus: a function that strips units and appends `rem`.
 * - Less cannot define value functions without a JavaScript plugin, so the
 *   result is a comment block that recommends the `rem` format.
 * - CSS: a CSS custom function (`@function --rem(--px)`), with a note that
 *   browser support is limited.
 * - JS/TS: an exported arrow function returning a string (`'1rem'`). Names
 *   with dashes become camelCase (`px-to-rem` → `pxToRem`).
 */
export function generateRemHelper(target: HelperTarget, functionName: string, base: number): string {
    const b = formatNumber(base, { precision: 4, leadingZero: true });
    const name = functionName;
    switch (target) {
        case 'scss':
            return [
                `// ${HEADER}`,
                `@use 'sass:math';`,
                ``,
                `/// Converts px to rem: ${name}(16) and ${name}(16px) both return ${formatNumber(16 / base, { precision: 4, leadingZero: true })}rem.`,
                `/// @param {Number} $px - Value in px, unitless or with px.`,
                `/// @param {Number} $base [${b}px] - Root font size.`,
                `@function ${name}($px, $base: ${b}px) {`,
                `  @if math.is-unitless($px) {`,
                `    $px: $px * 1px;`,
                `  }`,
                `  @if math.is-unitless($base) {`,
                `    $base: $base * 1px;`,
                `  }`,
                `  @if math.unit($px) != 'px' or math.unit($base) != 'px' {`,
                `    @error '${name}() expects px or unitless numbers, got #{$px} and #{$base}.';`,
                `  }`,
                `  @return math.div($px, $base) * 1rem;`,
                `}`,
                ``,
            ].join('\n');
        case 'sass':
            return [
                `// ${HEADER}`,
                `@use 'sass:math'`,
                ``,
                `/// Converts px to rem: ${name}(16) and ${name}(16px) both return ${formatNumber(16 / base, { precision: 4, leadingZero: true })}rem.`,
                `/// @param {Number} $px - Value in px, unitless or with px.`,
                `/// @param {Number} $base [${b}px] - Root font size.`,
                `@function ${name}($px, $base: ${b}px)`,
                `  @if math.is-unitless($px)`,
                `    $px: $px * 1px`,
                `  @if math.is-unitless($base)`,
                `    $base: $base * 1px`,
                `  @if math.unit($px) != 'px' or math.unit($base) != 'px'`,
                `    @error '${name}() expects px or unitless numbers, got #{$px} and #{$base}.'`,
                `  @return math.div($px, $base) * 1rem`,
                ``,
            ].join('\n');
        case 'stylus':
            return [
                `// ${HEADER}`,
                `// Converts px to rem: ${name}(16) and ${name}(16px) both return ${formatNumber(16 / base, { precision: 4, leadingZero: true })}rem.`,
                `${name}(value, base = ${b})`,
                `  unit(unit(value, '') / unit(base, ''), 'rem')`,
                ``,
            ].join('\n');
        case 'less':
            return [
                `// ${HEADER}`,
                `// Less cannot define functions that return a value, such as ${name}(16), without`,
                `// a JavaScript plugin (@plugin), so there is no plugin-free ${name}() helper.`,
                `// Use the \`rem\` format instead ("pxToRem.format": "rem", or "format": "rem" in`,
                `// .pxtoremrc.json): px values are written as rem directly (${b}px = 1rem).`,
                ``,
            ].join('\n');
        case 'css': {
            const fn = cssFunctionName(name);
            return [
                `/* ${HEADER} */`,
                `/*`,
                ` * ${fn}(16) returns ${formatNumber(16 / base, { precision: 4, leadingZero: true })}rem. Pass px values without the unit.`,
                ` * CSS custom functions are new and browser support is still limited, so`,
                ` * prefer the \`rem\` format preset ("pxToRem.format": "rem"), which writes rem`,
                ` * directly. To have conversions call this function instead, set`,
                ` * "pxToRem.format": "${fn}({px})".`,
                ` */`,
                `@function ${fn}(--px) returns <length> {`,
                `  result: calc(var(--px) / ${b} * 1rem);`,
                `}`,
                ``,
            ].join('\n');
        }
        case 'js': {
            const fn = jsIdentifier(name);
            return [
                `// ${HEADER}`,
                `/** Converts px to rem: ${fn}(16) and ${fn}('16px') both return '${formatNumber(16 / base, { precision: 4, leadingZero: true })}rem'. */`,
                `export const ${fn} = (px, base = ${b}) => \`\${parseFloat(px) / base}rem\`;`,
                ``,
            ].join('\n');
        }
        case 'ts': {
            const fn = jsIdentifier(name);
            return [
                `// ${HEADER}`,
                `/** Converts px to rem: ${fn}(16) and ${fn}('16px') both return '${formatNumber(16 / base, { precision: 4, leadingZero: true })}rem'. */`,
                `export const ${fn} = (px: number | \`\${number}px\`, base = ${b}): string =>`,
                `  \`\${(typeof px === 'number' ? px : parseFloat(px)) / base}rem\`;`,
                ``,
            ].join('\n');
        }
    }
}

/** Token file flavours. */
export type TokenFileFormat = 'css' | 'scss' | 'scss-map' | 'less' | 'stylus' | 'dtcg' | 'tailwind-v4';

/** Scales in px. */
export interface TokenScales {
    spacing: number[];
    fontSize: number[];
    radius: number[];
}

export interface TokenFileOptions {
    rootFontSize: number;
    units: 'rem' | 'px';
    /** Prepended to every name (`ds-` → `--ds-space-4`). Ignored for Tailwind v4, whose theme namespaces are fixed. */
    prefix: string;
    precision: number;
    leadingZero: boolean;
}

type TokenCategory = 'spacing' | 'font-size' | 'radius';

/** A token with its name parts. */
interface NamedToken {
    category: TokenCategory;
    /** Group name with prefix: `space`, `ds-font-size`, `spacing` (Tailwind). */
    group: string;
    /** Step key: `4`, `lg`, `2xl`, `full`. */
    key: string;
    /** `group-key`. */
    name: string;
    px: number;
}

/** Radii from this size on are pills; they are named `full` and always written in px. */
const PILL_RADIUS = 999;

/** Group names per format (Tailwind v4 uses its own theme namespaces). */
function groupNames(format: TokenFileFormat): Record<TokenCategory, string> {
    return format === 'tailwind-v4'
        ? { spacing: 'spacing', 'font-size': 'text', radius: 'radius' }
        : { spacing: 'space', 'font-size': 'font-size', radius: 'radius' };
}

function normalizeScale(values: number[]): number[] {
    const rounded = values.filter(v => Number.isFinite(v) && v >= 0).map(v => Math.round(v * 1000) / 1000);
    return [...new Set(rounded)].sort((a, b) => a - b);
}

/** `space-<px/4>` when every step is on the 4px grid (Tailwind numbering: 4 = 16px), else `space-1…n` in order. */
function spacingKeys(values: number[]): string[] {
    const onGrid = values.every(v => v % 4 === 0);
    return values.map((v, i) => String(onGrid ? v / 4 : i + 1));
}

/** `base` for the size closest to 16px, then sm, xs, 2xs, … below and lg, xl, 2xl, … above. */
function fontSizeKeys(values: number[]): string[] {
    let base = 0;
    values.forEach((v, i) => {
        if (Math.abs(v - 16) < Math.abs(values[base] - 16)) {
            base = i;
        }
    });
    return values.map((_, i) => {
        const offset = i - base;
        if (offset === 0) {
            return 'base';
        }
        if (offset < 0) {
            return offset === -1 ? 'sm' : offset === -2 ? 'xs' : `${-offset - 1}xs`;
        }
        return offset === 1 ? 'lg' : offset === 2 ? 'xl' : `${offset - 1}xl`;
    });
}

/** sm, md, lg, xl, 2xl, … in order; one pill radius (≥ 999px) becomes `full`. */
function radiusKeys(values: number[]): string[] {
    return values.map((v, i) => {
        if (v >= PILL_RADIUS) {
            return 'full';
        }
        return i === 0 ? 'sm' : i === 1 ? 'md' : i === 2 ? 'lg' : i === 3 ? 'xl' : `${i - 2}xl`;
    });
}

function namedTokens(format: TokenFileFormat, scales: TokenScales, options: TokenFileOptions): NamedToken[] {
    const groups = groupNames(format);
    const prefix = format === 'tailwind-v4' ? '' : options.prefix;
    const out: NamedToken[] = [];
    const add = (category: TokenCategory, values: number[], keys: string[]) => {
        const group = prefix + groups[category];
        values.forEach((px, i) => out.push({ category, group, key: keys[i], name: `${group}-${keys[i]}`, px }));
    };
    const spacing = normalizeScale(scales.spacing);
    add('spacing', spacing, spacingKeys(spacing));
    const fontSize = normalizeScale(scales.fontSize);
    add('font-size', fontSize, fontSizeKeys(fontSize));
    // Several pill radii (999px, 9999px) collapse into one `full` token.
    const radius = normalizeScale(scales.radius).filter((v, i, all) => v < PILL_RADIUS || i === all.findIndex(x => x >= PILL_RADIUS));
    add('radius', radius, radiusKeys(radius));
    return out;
}

/** Writes `4`, `md` or `'2xl'` as a Sass map key. */
function sassMapKey(key: string): string {
    return /^\d+$/.test(key) || /^[a-zA-Z_][\w-]*$/.test(key) ? key : `'${key}'`;
}

function reference(format: TokenFileFormat, token: NamedToken): string {
    switch (format) {
        case 'scss':
            return `$${token.name}`;
        case 'scss-map':
            return `map.get($${token.group}, ${sassMapKey(token.key)})`;
        case 'less':
            return `@${token.name}`;
        case 'stylus':
            return token.name;
        default:
            return `var(--${token.name})`;
    }
}

function valueOf(token: NamedToken, options: TokenFileOptions): { value: number; unit: 'rem' | 'px' } {
    const unit = options.units === 'px' || (token.category === 'radius' && token.px >= PILL_RADIUS) ? 'px' : 'rem';
    return { value: unit === 'px' ? token.px : token.px / options.rootFontSize, unit };
}

/** The value as CSS (`0.25rem`, `0`) and a px comment when the unit is not px. */
function cssValue(token: NamedToken, options: TokenFileOptions): { text: string; px?: string } {
    const style: NumberStyle = { precision: options.precision, leadingZero: options.leadingZero };
    const { value, unit } = valueOf(token, options);
    if (token.px === 0) {
        return { text: '0' };
    }
    const text = `${formatNumber(value, style)}${unit}`;
    return unit === 'px' ? { text } : { text, px: `${formatNumber(token.px, { precision: 2, leadingZero: true })}px` };
}

const SECTION_TITLES: Record<TokenCategory, string> = {
    spacing: 'Spacing',
    'font-size': 'Font sizes',
    radius: 'Radii',
};

function sections(tokens: NamedToken[]): NamedToken[][] {
    const order: TokenCategory[] = ['spacing', 'font-size', 'radius'];
    return order.map(c => tokens.filter(t => t.category === c)).filter(list => list.length > 0);
}

function dtcg(tokens: NamedToken[], options: TokenFileOptions): string {
    const root: Record<string, Record<string, unknown>> = {};
    for (const token of tokens) {
        const { value, unit } = valueOf(token, options);
        const rounded = Number(formatNumber(value, { precision: options.precision, leadingZero: true }));
        root[token.group] ??= {};
        root[token.group][token.key] = { $type: 'dimension', $value: { value: rounded, unit } };
    }
    return JSON.stringify(root, null, 2) + '\n';
}

/**
 * A token file for the scales.
 *
 * Naming: spacing → `space-<px/4>` when every step is on the 4px grid
 * (Tailwind numbering: `space-4` = 16px), otherwise `space-1…n` in order;
 * font sizes → `font-size-base` for the size closest to 16px with `sm`, `xs`,
 * `2xs`, … below and `lg`, `xl`, `2xl`, … above; radii → `radius-sm`, `md`,
 * `lg`, `xl`, `2xl`, … with a pill radius (≥ 999px) as `radius-full`, always
 * in px. Tailwind v4 uses its theme namespaces (`--spacing-*`, `--text-*`,
 * `--radius-*`) and ignores `prefix`. DTCG JSON groups tokens by
 * `space` / `font-size` / `radius` with dimension values in the 2025 object
 * form (`{ "value": 1, "unit": "rem" }`).
 */
export function generateTokenFile(format: TokenFileFormat, scales: TokenScales, options: TokenFileOptions): string {
    const tokens = namedTokens(format, scales, options);
    if (format === 'dtcg') {
        return dtcg(tokens, options);
    }
    const lines: string[] = [];
    const blockComment = format === 'css' || format === 'tailwind-v4';
    const comment = (text: string) => (blockComment ? `/* ${text} */` : `// ${text}`);
    lines.push(comment(HEADER));

    switch (format) {
        case 'css':
        case 'tailwind-v4': {
            lines.push(format === 'css' ? ':root {' : '@theme {');
            sections(tokens).forEach((list, i) => {
                if (i > 0) {
                    lines.push('');
                }
                lines.push(`  ${comment(SECTION_TITLES[list[0].category])}`);
                for (const token of list) {
                    const { text, px } = cssValue(token, options);
                    lines.push(`  --${token.name}: ${text};${px ? ' ' + comment(px) : ''}`);
                }
            });
            lines.push('}');
            break;
        }
        case 'scss-map': {
            lines.push(`// Use with @use 'sass:map'; and ${tokens[0] ? reference(format, tokens[0]) : 'map.get($space, 4)'}.`);
            for (const list of sections(tokens)) {
                lines.push('', `$${list[0].group}: (`);
                for (const token of list) {
                    const { text, px } = cssValue(token, options);
                    lines.push(`  ${sassMapKey(token.key)}: ${text},${px ? ' ' + comment(px) : ''}`);
                }
                lines.push(');');
            }
            break;
        }
        default: {
            const sigil = format === 'scss' ? '$' : format === 'less' ? '@' : '';
            for (const list of sections(tokens)) {
                lines.push('', comment(SECTION_TITLES[list[0].category]));
                for (const token of list) {
                    const { text, px } = cssValue(token, options);
                    const declaration = format === 'stylus' ? `${token.name} = ${text}` : `${sigil}${token.name}: ${text};`;
                    lines.push(`${declaration}${px ? ' ' + comment(px) : ''}`);
                }
            }
            break;
        }
    }
    return lines.join('\n') + '\n';
}

/**
 * The token names generateTokenFile uses, mapped to px, so callers can migrate
 * values to them. `name` is the flat name without sigil (`space-4`,
 * `ds-font-size-lg`, `text-lg` for Tailwind v4); `reference` is how to use it
 * in the format's language (`var(--space-4)`, `$space-4`,
 * `map.get($space, 4)`, `@space-4`, `space-4`; DTCG tokens are referenced as
 * the CSS custom properties Style Dictionary emits, `var(--space-4)`).
 */
export function tokenNamesFor(
    format: TokenFileFormat,
    scales: TokenScales,
    options: TokenFileOptions,
): { name: string; reference: string; px: number; category: 'spacing' | 'font-size' | 'radius' }[] {
    return namedTokens(format, scales, options).map(token => ({
        name: token.name,
        reference: reference(format, token),
        px: token.px,
        category: token.category,
    }));
}
